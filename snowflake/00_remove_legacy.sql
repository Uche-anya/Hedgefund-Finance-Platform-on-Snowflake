DROP TABLE IF EXISTS NORTHBRIDGE_DEV.RAW.SETTLEMENT_EVENTS;
DROP TABLE IF EXISTS NORTHBRIDGE_DEV.RAW.CORPORATE_ACTIONS;
DROP TABLE IF EXISTS NORTHBRIDGE_DEV.RAW.CORPORATE_ACTION_REVIEWS;
DROP TABLE IF EXISTS NORTHBRIDGE_DEV.RAW.BROKER_POSITIONS;
DROP TABLE IF EXISTS NORTHBRIDGE_DEV.RAW.FX_RATES;
DROP TABLE IF EXISTS NORTHBRIDGE_DEV.RAW.TREASURY_RATES;
DROP TABLE IF EXISTS NORTHBRIDGE_DEV.RAW.FUND_ADMIN_EVENTS;
DROP TABLE IF EXISTS NORTHBRIDGE_DEV.RAW.BANK_CASH_STATEMENTS;
DROP TABLE IF EXISTS NORTHBRIDGE_DEV.RAW.DIVIDEND_PAYMENT_EVENTS;
DROP TABLE IF EXISTS NORTHBRIDGE_DEV.RAW.TWO_YEAR_REPORTING;

-- Old upload locations and file formats are no longer used either.
DROP STAGE IF EXISTS NORTHBRIDGE_DEV.RAW.OMS_SAMPLE_20250106;
DROP STAGE IF EXISTS NORTHBRIDGE_DEV.RAW.MARKET_SAMPLE_20250106_08;
