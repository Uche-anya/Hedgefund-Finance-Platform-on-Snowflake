DROP STAGE IF EXISTS NORTHBRIDGE_DEV.RAW.FX_RATES_STAGE;
DROP STAGE IF EXISTS NORTHBRIDGE_DEV.RAW.TREASURY_RATES_STAGE;
DROP STAGE IF EXISTS NORTHBRIDGE_DEV.RAW.FUND_ADMIN_STAGE;
DROP STAGE IF EXISTS NORTHBRIDGE_DEV.RAW.BANK_CASH_STAGE;
DROP STAGE IF EXISTS NORTHBRIDGE_DEV.RAW.DIVIDEND_PAYMENT_STAGE;
DROP STAGE IF EXISTS NORTHBRIDGE_DEV.RAW.TWO_YEAR_REPORTING_STAGE;

DROP FILE FORMAT IF EXISTS NORTHBRIDGE_DEV.RAW.OMS_CSV;
DROP FILE FORMAT IF EXISTS NORTHBRIDGE_DEV.RAW.MARKET_CSV;
DROP FILE FORMAT IF EXISTS NORTHBRIDGE_DEV.RAW.HISTORICAL_PRICES_CSV;
DROP FILE FORMAT IF EXISTS NORTHBRIDGE_DEV.RAW.OMS_JSON;
