-- One-time reset, run through scripts/snow_admin.py as SYSADMIN.
-- Do not rerun after building new dbt models in DBT_DEV.
-- Keep NORTHBRIDGE_DEV.RAW: the new daily pipeline uses that schema.

USE ROLE SYSADMIN;
USE WAREHOUSE COMPUTE_WH;

-- See what is there before deleting it. Save this result if you want a record.
SELECT table_schema, table_name, table_type, row_count
FROM NORTHBRIDGE_DEV.INFORMATION_SCHEMA.TABLES
WHERE table_schema IN ('RAW', 'DBT_DEV', 'OPERATIONS')
ORDER BY table_schema, table_name;

-- These two schemas belong to the previous dbt and close pilots.
DROP SCHEMA IF EXISTS NORTHBRIDGE_DEV.DBT_DEV CASCADE;
DROP SCHEMA IF EXISTS NORTHBRIDGE_DEV.OPERATIONS CASCADE;

-- Stop the old pipes before removing their source tables and stages.
DROP PIPE IF EXISTS NORTHBRIDGE_DEV.RAW.OMS_EVENTS_PIPE;
DROP PIPE IF EXISTS NORTHBRIDGE_DEV.RAW.SETTLEMENT_EVENTS_PIPE;

-- Old RAW tables. The new DAILY_* tables are deliberately absent.
DROP TABLE IF EXISTS NORTHBRIDGE_DEV.RAW.EXECUTIONS;
DROP TABLE IF EXISTS NORTHBRIDGE_DEV.RAW.ALLOCATIONS;
DROP TABLE IF EXISTS NORTHBRIDGE_DEV.RAW.CLOSING_PRICES;
DROP TABLE IF EXISTS NORTHBRIDGE_DEV.RAW.REPLAY_INPUTS;
