-- A fixed copy of current daily inputs for dbt integration tests.
-- No producer, pipe or scheduled task writes to this database.
USE ROLE SYSADMIN;
CREATE DATABASE IF NOT EXISTS NORTHBRIDGE_TEST
    COMMENT = 'Isolated daily-pipeline test inputs and dbt models';
CREATE SCHEMA IF NOT EXISTS NORTHBRIDGE_TEST.RAW;
CREATE SCHEMA IF NOT EXISTS NORTHBRIDGE_TEST.DBT_TEST;

CREATE TABLE IF NOT EXISTS NORTHBRIDGE_TEST.RAW.DAILY_OMS_EVENTS
    CLONE NORTHBRIDGE_DEV.RAW.DAILY_OMS_EVENTS;
CREATE TABLE IF NOT EXISTS NORTHBRIDGE_TEST.RAW.DAILY_PRICE_EVENTS
    CLONE NORTHBRIDGE_DEV.RAW.DAILY_PRICE_EVENTS;
CREATE TABLE IF NOT EXISTS NORTHBRIDGE_TEST.RAW.DAILY_SETTLEMENT_EVENTS
    CLONE NORTHBRIDGE_DEV.RAW.DAILY_SETTLEMENT_EVENTS;
CREATE TABLE IF NOT EXISTS NORTHBRIDGE_TEST.RAW.DAILY_OPENING_EVENTS
    CLONE NORTHBRIDGE_DEV.RAW.DAILY_OPENING_EVENTS;
CREATE TABLE IF NOT EXISTS NORTHBRIDGE_TEST.RAW.DAILY_BANK_STATEMENTS
    CLONE NORTHBRIDGE_DEV.RAW.DAILY_BANK_STATEMENTS;
CREATE TABLE IF NOT EXISTS NORTHBRIDGE_TEST.RAW.DAILY_DELIVERIES
    CLONE NORTHBRIDGE_DEV.RAW.DAILY_DELIVERIES;
CREATE TABLE IF NOT EXISTS NORTHBRIDGE_TEST.RAW.DAILY_DIVIDEND_EVENTS
    CLONE NORTHBRIDGE_DEV.RAW.DAILY_DIVIDEND_EVENTS;
CREATE TABLE IF NOT EXISTS NORTHBRIDGE_TEST.RAW.DIVIDEND_REVIEWS
    CLONE NORTHBRIDGE_DEV.RAW.DIVIDEND_REVIEWS;
CREATE TABLE IF NOT EXISTS NORTHBRIDGE_TEST.RAW.DAILY_CLOSE_RUNS
    CLONE NORTHBRIDGE_DEV.RAW.DAILY_CLOSE_RUNS;
CREATE TABLE IF NOT EXISTS NORTHBRIDGE_TEST.RAW.SECURITY_MAPPINGS
    CLONE NORTHBRIDGE_DEV.RAW.SECURITY_MAPPINGS;
CREATE TABLE IF NOT EXISTS NORTHBRIDGE_TEST.RAW.US_EQUITY_MARKET_CLOSED
    CLONE NORTHBRIDGE_DEV.RAW.US_EQUITY_MARKET_CLOSED;

USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS NORTHBRIDGE_DBT_TEST;
GRANT ROLE NORTHBRIDGE_DBT_TEST TO ROLE SYSADMIN;
GRANT ROLE NORTHBRIDGE_DBT_TEST TO USER NORTHBRIDGE_DBT;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE NORTHBRIDGE_DBT_TEST;
GRANT USAGE ON DATABASE NORTHBRIDGE_TEST TO ROLE NORTHBRIDGE_DBT_TEST;
GRANT USAGE ON SCHEMA NORTHBRIDGE_TEST.RAW TO ROLE NORTHBRIDGE_DBT_TEST;
GRANT SELECT ON ALL TABLES IN SCHEMA NORTHBRIDGE_TEST.RAW
    TO ROLE NORTHBRIDGE_DBT_TEST;
GRANT USAGE ON SCHEMA NORTHBRIDGE_TEST.DBT_TEST TO ROLE NORTHBRIDGE_DBT_TEST;
GRANT CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE DBT PROJECT
    ON SCHEMA NORTHBRIDGE_TEST.DBT_TEST TO ROLE NORTHBRIDGE_DBT_TEST;
