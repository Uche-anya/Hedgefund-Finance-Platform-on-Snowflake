    TO ROLE NORTHBRIDGE_INGEST_TEST;
GRANT SELECT, INSERT ON TABLE NORTHBRIDGE_TEST.RAW.DAILY_OMS_EVENTS
    TO ROLE NORTHBRIDGE_INGEST_TEST;
