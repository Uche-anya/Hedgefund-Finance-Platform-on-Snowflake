    TO ROLE NORTHBRIDGE_INGEST_TEST;
GRANT SELECT, INSERT ON TABLE NORTHBRIDGE_TEST.RAW.DAILY_PRICE_EVENTS
    TO ROLE NORTHBRIDGE_INGEST_TEST;
GRANT SELECT, INSERT ON TABLE NORTHBRIDGE_TEST.RAW.DAILY_DIVIDEND_EVENTS
    TO ROLE NORTHBRIDGE_INGEST_TEST;
GRANT SELECT, INSERT ON TABLE NORTHBRIDGE_TEST.RAW.DAILY_OPENING_EVENTS
    TO ROLE NORTHBRIDGE_INGEST_TEST;
GRANT SELECT, INSERT ON TABLE NORTHBRIDGE_TEST.RAW.DAILY_BANK_STATEMENTS
    TO ROLE NORTHBRIDGE_INGEST_TEST;
GRANT SELECT ON TABLE NORTHBRIDGE_TEST.RAW.DAILY_CLOSE_RUNS
    TO ROLE NORTHBRIDGE_INGEST_TEST;
GRANT OPERATE, MONITOR ON PIPE NORTHBRIDGE_TEST.RAW.DAILY_OMS_PIPE
    TO ROLE NORTHBRIDGE_INGEST_TEST;
GRANT OPERATE, MONITOR ON PIPE NORTHBRIDGE_TEST.RAW.DAILY_SETTLEMENT_PIPE
    TO ROLE NORTHBRIDGE_INGEST_TEST;
