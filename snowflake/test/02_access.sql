-- TEST loader can write only TEST deliveries. CI's dbt user remains read-only on RAW.
USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS NORTHBRIDGE_INGEST_TEST;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE NORTHBRIDGE_INGEST_TEST;
GRANT USAGE ON DATABASE NORTHBRIDGE_TEST TO ROLE NORTHBRIDGE_INGEST_TEST;
GRANT USAGE ON SCHEMA NORTHBRIDGE_TEST.RAW TO ROLE NORTHBRIDGE_INGEST_TEST;
GRANT READ, WRITE ON STAGE NORTHBRIDGE_TEST.RAW.DAILY_LANDING
    TO ROLE NORTHBRIDGE_INGEST_TEST;
