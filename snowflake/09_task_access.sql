-- Give the dbt service role ownership of its project and task graph.
USE ROLE SECURITYADMIN;
GRANT CREATE DBT PROJECT, CREATE TASK, CREATE PROCEDURE, CREATE STAGE
    ON SCHEMA NORTHBRIDGE_DEV.DBT_DEV TO ROLE NORTHBRIDGE_DBT_DEV;

USE ROLE ACCOUNTADMIN;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE NORTHBRIDGE_DBT_DEV;

-- The task checks the same raw deliveries that the local readiness check reads.
USE ROLE SECURITYADMIN;
GRANT SELECT ON TABLE NORTHBRIDGE_DEV.RAW.DAILY_SETTLEMENT_EVENTS
    TO ROLE NORTHBRIDGE_DBT_DEV;
GRANT SELECT ON TABLE NORTHBRIDGE_DEV.RAW.DAILY_OPENING_EVENTS
    TO ROLE NORTHBRIDGE_DBT_DEV;
GRANT SELECT, INSERT ON TABLE NORTHBRIDGE_DEV.RAW.DAILY_CLOSE_RUNS
    TO ROLE NORTHBRIDGE_DBT_DEV;

-- The hosted producer reads the previous checked NAV before making another day.
GRANT USAGE ON SCHEMA NORTHBRIDGE_DEV.DBT_DEV
    TO ROLE NORTHBRIDGE_INGEST_DEV;
GRANT SELECT ON TABLE NORTHBRIDGE_DEV.DBT_DEV.FCT_NAV_DAILY
    TO ROLE NORTHBRIDGE_INGEST_DEV;
