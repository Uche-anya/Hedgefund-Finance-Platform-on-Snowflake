-- Separate loader and dbt roles. Neither inherits the DEV or TEST role.
USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS NORTHBRIDGE_INGEST_PROD;
CREATE ROLE IF NOT EXISTS NORTHBRIDGE_DBT_PROD;

GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE NORTHBRIDGE_INGEST_PROD;
GRANT USAGE ON DATABASE NORTHBRIDGE_PROD TO ROLE NORTHBRIDGE_INGEST_PROD;
GRANT USAGE ON SCHEMA NORTHBRIDGE_PROD.RAW TO ROLE NORTHBRIDGE_INGEST_PROD;
GRANT READ, WRITE ON STAGE NORTHBRIDGE_PROD.RAW.DAILY_LANDING
    TO ROLE NORTHBRIDGE_INGEST_PROD;
GRANT USAGE ON FILE FORMAT NORTHBRIDGE_PROD.RAW.DAILY_JSON
    TO ROLE NORTHBRIDGE_INGEST_PROD;
GRANT SELECT, INSERT ON TABLE NORTHBRIDGE_PROD.RAW.DAILY_OMS_EVENTS
    TO ROLE NORTHBRIDGE_INGEST_PROD;
GRANT SELECT, INSERT ON TABLE NORTHBRIDGE_PROD.RAW.DAILY_SETTLEMENT_EVENTS
    TO ROLE NORTHBRIDGE_INGEST_PROD;
GRANT SELECT, INSERT ON TABLE NORTHBRIDGE_PROD.RAW.DAILY_PRICE_EVENTS
    TO ROLE NORTHBRIDGE_INGEST_PROD;
GRANT SELECT, INSERT ON TABLE NORTHBRIDGE_PROD.RAW.DAILY_DIVIDEND_EVENTS
    TO ROLE NORTHBRIDGE_INGEST_PROD;
GRANT SELECT, INSERT ON TABLE NORTHBRIDGE_PROD.RAW.DAILY_OPENING_EVENTS
    TO ROLE NORTHBRIDGE_INGEST_PROD;
GRANT SELECT, INSERT ON TABLE NORTHBRIDGE_PROD.RAW.DAILY_BANK_STATEMENTS
    TO ROLE NORTHBRIDGE_INGEST_PROD;
GRANT SELECT, INSERT, UPDATE ON TABLE NORTHBRIDGE_PROD.RAW.DAILY_DELIVERIES
    TO ROLE NORTHBRIDGE_INGEST_PROD;
GRANT SELECT ON TABLE NORTHBRIDGE_PROD.RAW.DAILY_CLOSE_RUNS
    TO ROLE NORTHBRIDGE_INGEST_PROD;
GRANT OPERATE, MONITOR ON PIPE NORTHBRIDGE_PROD.RAW.DAILY_OMS_PIPE
    TO ROLE NORTHBRIDGE_INGEST_PROD;
GRANT OPERATE, MONITOR ON PIPE NORTHBRIDGE_PROD.RAW.DAILY_SETTLEMENT_PIPE
    TO ROLE NORTHBRIDGE_INGEST_PROD;

GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE NORTHBRIDGE_DBT_PROD;
GRANT USAGE ON DATABASE NORTHBRIDGE_PROD TO ROLE NORTHBRIDGE_DBT_PROD;
GRANT USAGE ON SCHEMA NORTHBRIDGE_PROD.RAW TO ROLE NORTHBRIDGE_DBT_PROD;
GRANT SELECT ON TABLE NORTHBRIDGE_PROD.RAW.DAILY_OMS_EVENTS
    TO ROLE NORTHBRIDGE_DBT_PROD;
GRANT SELECT ON TABLE NORTHBRIDGE_PROD.RAW.DAILY_SETTLEMENT_EVENTS
    TO ROLE NORTHBRIDGE_DBT_PROD;
GRANT SELECT ON TABLE NORTHBRIDGE_PROD.RAW.DAILY_PRICE_EVENTS
    TO ROLE NORTHBRIDGE_DBT_PROD;
GRANT SELECT ON TABLE NORTHBRIDGE_PROD.RAW.DAILY_DIVIDEND_EVENTS
    TO ROLE NORTHBRIDGE_DBT_PROD;
GRANT SELECT ON TABLE NORTHBRIDGE_PROD.RAW.DAILY_OPENING_EVENTS
    TO ROLE NORTHBRIDGE_DBT_PROD;
GRANT SELECT ON TABLE NORTHBRIDGE_PROD.RAW.DAILY_BANK_STATEMENTS
    TO ROLE NORTHBRIDGE_DBT_PROD;
GRANT SELECT ON TABLE NORTHBRIDGE_PROD.RAW.DAILY_DELIVERIES
    TO ROLE NORTHBRIDGE_DBT_PROD;
GRANT SELECT ON TABLE NORTHBRIDGE_PROD.RAW.DIVIDEND_REVIEWS
    TO ROLE NORTHBRIDGE_DBT_PROD;
GRANT SELECT ON TABLE NORTHBRIDGE_PROD.RAW.SECURITY_MAPPINGS
    TO ROLE NORTHBRIDGE_DBT_PROD;
GRANT SELECT ON TABLE NORTHBRIDGE_PROD.RAW.DAILY_CLOSE_RUNS
    TO ROLE NORTHBRIDGE_DBT_PROD;
GRANT INSERT ON TABLE NORTHBRIDGE_PROD.RAW.DAILY_CLOSE_RUNS
    TO ROLE NORTHBRIDGE_DBT_PROD;
GRANT USAGE ON SCHEMA NORTHBRIDGE_PROD.DBT_PROD TO ROLE NORTHBRIDGE_DBT_PROD;
GRANT CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE DBT PROJECT
    ON SCHEMA NORTHBRIDGE_PROD.DBT_PROD TO ROLE NORTHBRIDGE_DBT_PROD;

GRANT USAGE ON SCHEMA NORTHBRIDGE_PROD.DBT_PROD
    TO ROLE NORTHBRIDGE_INGEST_PROD;
