-- A review applies to one version of a provider event. Keep prior decisions.
USE ROLE SYSADMIN;

CREATE TABLE IF NOT EXISTS NORTHBRIDGE_DEV.RAW.DIVIDEND_REVIEWS (
    review_id VARCHAR,
    event_id VARCHAR,
    terms_hash VARCHAR,
    decision VARCHAR,
    instrument_id VARCHAR,
    reviewer VARCHAR,
    reason VARCHAR,
    reviewed_at TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

USE ROLE SECURITYADMIN;
GRANT SELECT ON TABLE NORTHBRIDGE_DEV.RAW.DIVIDEND_REVIEWS
    TO ROLE NORTHBRIDGE_DBT_DEV;
GRANT SELECT ON TABLE NORTHBRIDGE_DEV.RAW.DAILY_CLOSE_RUNS
    TO ROLE NORTHBRIDGE_DBT_DEV;
