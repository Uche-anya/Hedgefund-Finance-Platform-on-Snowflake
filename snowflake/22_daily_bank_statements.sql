USE ROLE SYSADMIN;

CREATE TABLE IF NOT EXISTS NORTHBRIDGE_DEV.RAW.DAILY_BANK_STATEMENTS (
    payload VARIANT,
    source_file VARCHAR,
    source_row_number NUMBER,
    loaded_at TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

USE ROLE SECURITYADMIN;
GRANT SELECT, INSERT ON TABLE NORTHBRIDGE_DEV.RAW.DAILY_BANK_STATEMENTS
    TO ROLE NORTHBRIDGE_INGEST_DEV;
GRANT SELECT ON TABLE NORTHBRIDGE_DEV.RAW.DAILY_BANK_STATEMENTS
    TO ROLE NORTHBRIDGE_DBT_DEV;

-- The bank simulator reads booked dividend exposure only to stop when a
-- payment needs separate bank evidence. It never uses dbt to set a balance.
GRANT SELECT ON TABLE NORTHBRIDGE_DEV.DBT_DEV.FCT_DIVIDEND_EXPOSURE
    TO ROLE NORTHBRIDGE_INGEST_DEV;
